"""
[GAP-REPS] Cold-start vs warm-start comparison for REPS under asymmetry and failures,
mirroring the paper's fig_4 (asymmetric) and fig_7 (failures) setups.

What the paper does (htsim/sim/datacenter/run_collective.py, run_failures.py):
  fig_4 "ai"  : 128-host 2-tier fat tree, allreduce.cm (64-host ring), -failed 4
                -down_ratio 0.25 (4 uplinks of ToR 0 at 1/4 speed, smaller queues/ECN).
  fig_7       : 32-host 2-tier fat tree, allreduce (16-host ring) / permutation / DC
                trace, -failures_input <file> (random cables/switches fail; placement is
                generated once, cached in failures_input/saved/, reused by later runs).
  Both use -connections_mapping (warm start ON) and -disable_trim (trimming off, so
  losses become timeouts, which is what triggers REPS freezing mode).

What this script does: the same scenarios, each with the cold/warm grid
  {freezing (REPS), oblivious} x {connections_mapping off (cold), on (warm)}.
  oblivious keeps no EV state, so its off/on difference isolates cwnd carry-over.
  Only workloads with recurring src/dst pairs (allreduce) can show warm starts.

Isolation from the artifact:
  Each run executes in its own working directory under <out_dir>/sim/<scenario>/<run>/.
  With -other_location the simulator reads/writes failure placements in
  <cwd>/../failures_input/saved/, i.e. a private per-scenario cache, so the repo's
  htsim/sim/failures_input/saved/ is never touched and every algorithm/mapping of a
  scenario sees the same failed components.

Stages: equiv | run | analyze (default: all). Examples:
  python3 gap_cold_warm_asym.py --dry-run
  python3 gap_cold_warm_asym.py --stage run --scenarios ar32_sym ar32_fail_one_cable
  python3 gap_cold_warm_asym.py --stage analyze
"""


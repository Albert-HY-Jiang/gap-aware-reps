def label_flows(df, mapping_on):
    """Add occurrence index per src/dst pair, warm flag, gap and buffer-sharing flag.

    Mirrors connections_mapping: at start, a flow inherits the buffer of the same-pair
    flow that finished most recently (any earlier one, not just the immediately previous).
    If the immediately previous same-pair flow is still running at that moment, the
    inherited buffer object may also be in use by another running flow (shared_buffer).
    """
    import bisect
    import pandas as pd

    df = df.sort_values("start_time_us").copy()
    df["occurrence"] = df.groupby(["src", "dst"]).cumcount()
    last_fin = pd.Series(float("nan"), index=df.index)
    for _, g in df.groupby(["src", "dst"]):
        fins = sorted(f for f in g["finish_time_us"] if f >= 0)
        for idx, start in zip(g.index, g["start_time_us"]):
            k = bisect.bisect_right(fins, start)
            if k:
                last_fin[idx] = fins[k - 1]
    prev_finish = df.groupby(["src", "dst"])["finish_time_us"].shift(1)
    df["warm"] = bool(mapping_on) & last_fin.notna()
    df["gap_us"] = (df["start_time_us"] - last_fin).where(last_fin.notna())
    df["shared_buffer"] = df["warm"] & (prev_finish > df["start_time_us"])
    return df


def parse_log(log_path):
    """Run-level facts the CSV does not carry: packet drops and freeze-mode activity."""
    text = log_path.read_text(errors="replace") if log_path.exists() else ""
    m = re.findall(r"Total number of dropped packets: (\d+)", text)
    return {
        "dropped_pkts": int(m[-1]) if m else 0,
        "freeze_msgs": len(re.findall(r"started freezing mode", text)),
        "degraded_links": len(re.findall(r"^Failure: ", text, re.M)),
    }


def load_runs(runs_dir, scenarios):
    """All flows from all runs (tagged from .json metadata) + one row per run."""
    import pandas as pd

    frames, runs = [], []
    for meta_path in sorted(runs_dir.glob("*.json")):
        meta = json.loads(meta_path.read_text())
        if meta["scenario"] not in scenarios:
            continue
        csv = meta_path.with_suffix(".csv")
        if meta.get("rc", 0) != 0:
            print(f"[analyze] skipping {meta_path.stem}: rc={meta.get('rc')}")
            continue
        if not csv.exists():
            print(f"[analyze] missing CSV for {meta_path.stem}")
            continue
        df = pd.read_csv(csv)
        if df.empty:
            continue
        df = label_flows(df, meta["mapping"] == "on")
        for key in ("scenario", "algo", "mapping", "seed"):
            df[key] = meta[key]
        frames.append(df)
        runs.append(dict({k: meta.get(k) for k in ("scenario", "ref", "algo", "mapping", "seed")},
                         **parse_log(meta_path.with_suffix(".log"))))
    if not frames:
        return None, None
    return pd.concat(frames, ignore_index=True), pd.DataFrame(runs)


def stage_analyze(cfg):
    import pandas as pd
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    df, runs_meta = load_runs(cfg["out_dir"] / "runs", set(cfg["scenarios"]))
    if df is None:
        print("[analyze] no runs found in", cfg["out_dir"] / "runs")
        return
    scenarios = [s for s in cfg["scenarios"] if s in set(df["scenario"])]
    keys = ["scenario", "algo", "mapping"]

    unfinished = (df["finish_time_us"] < 0).sum()
    if unfinished:
        print(f"[analyze] WARNING: {unfinished} flows did not finish before -end; "
              f"excluded from FCT, and their runs get no JCT (raise end_us)")
    f_all = df[df["algo"] == "freezing"]
    bad = f_all[f_all["random_ev_packets"] + f_all["cached_ev_packets"] != f_all["packets_sent"]]
    print(f"[analyze] consistency random+cached==packets_sent: "
          f"{'OK' if bad.empty else f'{len(bad)} rows FAIL'}")

    df["fct_us"] = (df["finish_time_us"] - df["start_time_us"]).where(df["finish_time_us"] >= 0)
    df["cold_frac"] = df["cache_empty_sends"] / df["packets_sent"]
    df["cached_frac"] = df["cached_ev_packets"] / df["packets_sent"]
    acks = df["ack_ecn"] + df["ack_no_ecn"]
    df["ecn_rate"] = (df["ack_ecn"] / acks).where(acks > 0)   # only counted for freezing

    out = cfg["out_dir"] / "analysis"
    out.mkdir(parents=True, exist_ok=True)
    df.to_csv(out / "flows_all.csv", index=False)

    # Run level: job completion time of the whole allreduce + log facts.
    runs = df.groupby(keys + ["seed"]).agg(
        jct_end=("finish_time_us", "max"),
        jct_start=("start_time_us", "min"),
        unfinished=("finish_time_us", lambda s: (s < 0).sum()),
    ).reset_index()
    runs["jct_us"] = (runs["jct_end"] - runs["jct_start"]).where(runs["unfinished"] == 0)
    runs = runs.merge(runs_meta, on=keys + ["seed"], how="left")
    runs.to_csv(out / "runs.csv", index=False)
    run_level = runs.groupby(keys).agg(jct_mean_us=("jct_us", "mean"),
                                       dropped_pkts=("dropped_pkts", "mean"),
                                       freeze_msgs=("freeze_msgs", "mean"),
                                       degraded_links=("degraded_links", "max"))

    # Flow level, excluding each pair's first flow (cold in every condition).
    later = df[df["occurrence"] > 0]
    if later.empty:
        later = df   # workloads without recurring pairs (e.g. permutation)
    summary = later.groupby(keys).agg(
        flows=("fct_us", "size"),
        warm_flows=("warm", "sum"),
        fct_med_us=("fct_us", "median"),
        fct_p99_us=("fct_us", lambda s: s.quantile(0.99)),
        pkts_sent=("packets_sent", "mean"),
        cache_empty_sends=("cache_empty_sends", "mean"),
        cold_frac=("cold_frac", "mean"),
        ecn_rate=("ecn_rate", "mean"),
        freeze_entries=("freeze_entries", "mean"),
        gap_med_us=("gap_us", "median"),
    ).join(run_level)
    summary = summary.reindex(scenarios, level=0).round(4)
    summary.to_csv(out / "summary.csv")
    with pd.option_context("display.width", 250, "display.max_columns", 30):
        print("\n[analyze] per condition (flows exclude first flow of each pair; "
              "jct/drops/freeze per run, mean over seeds):\n")
        print(summary)

    def stat(scen, algo, mapping, col, how="median"):
        s = later[(later.scenario == scen) & (later.algo == algo) & (later.mapping == mapping)][col].dropna()
        if not len(s):
            return float("nan")
        return s.median() if how == "median" else s.mean()

    def runv(scen, algo, mapping, col):
        try:
            return run_level.loc[(scen, algo, mapping), col]
        except KeyError:
            return float("nan")

    rows, warnings = [], []
    for scen in scenarios:
        r = {"scenario": scen}
        r["reps_vs_obl_jct_cold"] = runv(scen, "oblivious", "off", "jct_mean_us") / runv(scen, "freezing", "off", "jct_mean_us")
        r["reps_vs_obl_jct_warm"] = runv(scen, "oblivious", "on", "jct_mean_us") / runv(scen, "freezing", "on", "jct_mean_us")
        r["warm_speedup_jct_reps"] = runv(scen, "freezing", "off", "jct_mean_us") / runv(scen, "freezing", "on", "jct_mean_us")
        r["warm_speedup_jct_obl"] = runv(scen, "oblivious", "off", "jct_mean_us") / runv(scen, "oblivious", "on", "jct_mean_us")
        r["warm_speedup_fct_reps"] = stat(scen, "freezing", "off", "fct_us") / stat(scen, "freezing", "on", "fct_us")
        r["warm_speedup_fct_obl"] = stat(scen, "oblivious", "off", "fct_us") / stat(scen, "oblivious", "on", "fct_us")
        r["random_sends_cold"] = stat(scen, "freezing", "off", "cache_empty_sends", "mean")
        r["random_sends_warm"] = stat(scen, "freezing", "on", "cache_empty_sends", "mean")
        r["ecn_rate_cold"] = stat(scen, "freezing", "off", "ecn_rate", "mean")
        r["ecn_rate_warm"] = stat(scen, "freezing", "on", "ecn_rate", "mean")
        r["drops_reps_cold"] = runv(scen, "freezing", "off", "dropped_pkts")
        rows.append(r)

        # Did the perturbation change anything compared with its reference scenario?
        ref = CONFIG["scenarios"][scen].get("ref")
        if ref in scenarios:
            same = True
            for algo in ("freezing", "oblivious"):
                a, b = runv(scen, algo, "off", "jct_mean_us"), runv(ref, algo, "off", "jct_mean_us")
                same &= (a == b)
            no_signal = (not (r["ecn_rate_cold"] > 0)) and not (r["drops_reps_cold"] > 0)
            if same:
                warnings.append(f"'{scen}' has exactly the same JCT as '{ref}': the failure/"
                                f"asymmetry is not on any path this workload uses.")
            elif no_signal:
                warnings.append(f"'{scen}' differs from '{ref}' but shows no ECN and no drops "
                                f"for REPS: the perturbation barely touches the traffic.")
    comp = pd.DataFrame(rows).set_index("scenario").round(4)
    comp.to_csv(out / "comparisons.csv")
    with pd.option_context("display.width", 250, "display.max_columns", 30):
        print("\n[analyze] comparisons (ratios > 1 mean the second condition is faster):\n")
        print(comp.T)
    for w in warnings:
        print(f"\n[analyze] WARNING: {w}")

    # Plots.
    n = len(scenarios)
    ncol = min(3, n)
    nrow = (n + ncol - 1) // ncol
    fig, axes = plt.subplots(nrow, ncol, figsize=(5 * ncol, 3.8 * nrow), squeeze=False)
    for ax, scen in zip(axes.flat, scenarios):
        for (algo, mapping), g in later[later.scenario == scen].groupby(["algo", "mapping"]):
            s = g["fct_us"].dropna().sort_values()
            if len(s):
                ax.plot(s.values, [i / len(s) for i in range(1, len(s) + 1)],
                        label=f"{algo}, map {mapping}")
        ax.set_title(scen, fontsize=10)
        ax.set_xlabel("FCT (us)")
        ax.set_ylabel("CDF")
        ax.legend(fontsize=7)
    for ax in list(axes.flat)[n:]:
        ax.axis("off")
    fig.tight_layout()
    fig.savefig(out / "fct_cdf.png", dpi=150)

    metrics = [("cache_empty_sends", "random sends (cache empty)"),
               ("ecn_rate", "ECN rate"), ("fct_us", "FCT (us)")]
    fig, axes = plt.subplots(n, len(metrics), figsize=(4 * len(metrics), 3 * n), squeeze=False)
    for row, scen in zip(axes, scenarios):
        f = later[(later.scenario == scen) & (later.algo == "freezing")]
        for ax, (col, title) in zip(row, metrics):
            data = [f[f.mapping == m][col].dropna().values for m in ("off", "on")]
            ax.boxplot(data, labels=["cold (map off)", "warm (map on)"])
            ax.set_title(f"{scen} / freezing: {title}", fontsize=8)
    fig.tight_layout()
    fig.savefig(out / "freezing_cold_vs_warm.png", dpi=150)
    print(f"\n[analyze] wrote {out}/summary.csv, comparisons.csv, runs.csv, flows_all.csv, "
          f"fct_cdf.png, freezing_cold_vs_warm.png")


# ----------------------------------- main -----------------------------------------------

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=["all", "equiv", "run", "analyze"], default="all")
    ap.add_argument("--scenarios", nargs="+",
                    help=f"scenarios to run/analyze (default: CONFIG default_scenarios); "
                         f"known: {', '.join(CONFIG['scenarios'])}")
    ap.add_argument("--seeds", type=int, nargs="+", help="override CONFIG seeds")
    ap.add_argument("--jobs", type=int, help="override CONFIG jobs")
    ap.add_argument("--end", type=int, help="override CONFIG end_us")
    ap.add_argument("--out", help="override CONFIG out_dir")
    ap.add_argument("--fresh-failures", action="store_true",
                    help="delete cached failure placements and generate new ones")
    ap.add_argument("--dry-run", action="store_true", help="print commands without running")
    args = ap.parse_args()

    cfg = dict(CONFIG)
    names = args.scenarios or CONFIG["default_scenarios"]
    unknown = set(names) - set(CONFIG["scenarios"])
    if unknown:
        sys.exit(f"unknown scenarios {sorted(unknown)}; known: {list(CONFIG['scenarios'])}")
    cfg["scenarios"] = {s: CONFIG["scenarios"][s] for s in names}
    if args.seeds: cfg["seeds"] = args.seeds
    if args.jobs: cfg["jobs"] = args.jobs
    if args.end: cfg["end_us"] = args.end
    if args.out: cfg["out_dir"] = Path(args.out).resolve()
    cfg["out_dir"] = Path(cfg["out_dir"])
    cfg["out_dir"].mkdir(parents=True, exist_ok=True)

    if not Path(cfg["binary"]).exists():
        sys.exit(f"simulator not found: {cfg['binary']} (build htsim/sim then htsim/sim/datacenter)")

    if args.stage in ("all", "equiv"):
        if not stage_equiv(cfg, args.dry_run) and args.stage == "all":
            sys.exit("equivalence check failed; not running the grid")
    if args.stage in ("all", "run"):
        stage_run(cfg, args.dry_run, args.fresh_failures)
    if args.stage in ("all", "analyze") and not args.dry_run:
        stage_analyze(cfg)


if __name__ == "__main__":
    main()

def stage_equiv(cfg, dry_run):
    print("[equiv] original vs instrumented binary, same seed")
    out = cfg["out_dir"] / "equiv"
    out.mkdir(parents=True, exist_ok=True)
    if not Path(cfg["orig_binary"]).exists():
        print(f"  original binary not found at {cfg['orig_binary']}; skipping")
        return True

    runs = {}
    for case, extra in cfg["equiv_cases"].items():
        args = cfg["equiv_args"] + extra
        runs[f"{case}_orig"] = [cfg["orig_binary"]] + args
        runs[f"{case}_new"] = [cfg["binary"]] + args
        runs[f"{case}_new_csv"] = ([cfg["binary"]] + args
                                   + ["-reps_stats_csv", out / f"{case}_stats.csv"])
    with ThreadPoolExecutor(max_workers=max(1, cfg["jobs"])) as ex:
        futs = {k: ex.submit(run_cmd, c, out / f"{k}.log", cfg["timeout_s"], dry_run)
                for k, c in runs.items()}
        results = {k: f.result() for k, f in futs.items()}
    if dry_run:
        return True
    for k, (rc, dt) in results.items():
        print(f"  {k:16s} rc={rc} {dt:.1f}s")

    def finish_lines(name):
        lines = (out / f"{name}.log").read_text().splitlines()
        return sorted(l for l in lines if "finished at" in l)

    ok = True
    for case in cfg["equiv_cases"]:
        ref = finish_lines(f"{case}_orig")
        ok &= bool(ref)
        for k in ("new", "new_csv"):
            same = finish_lines(f"{case}_{k}") == ref
            ok &= same
            print(f"  {case}/{k:8s} finish lines identical to orig: {same} ({len(ref)} flows)")
    print("[equiv] PASS" if ok else "[equiv] FAIL - instrumentation changed behaviour?")
    return ok


# ----------------------------------- run ------------------------------------------------

def run_name(scenario, algo, mapping, seed):
    return f"{scenario}__{algo}_map{'on' if mapping else 'off'}_s{seed}"


def build_jobs(cfg, out):
    jobs = []
    for scen_name in cfg["scenarios"]:
        scen = CONFIG["scenarios"][scen_name]
        wl = cfg["workloads"][scen["workload"]]
        for label, p in (("topology", wl["topo"]), ("traffic matrix", wl["tm"])):
            if not Path(p).exists():
                sys.exit(f"[run] {scen_name}: {label} not found: {p}")
        extra = list(scen.get("args", []))
        if scen.get("failures_input"):
            fpath = FAILS / scen["failures_input"]
            if not fpath.exists():
                sys.exit(f"[run] {scen_name}: failure input not found: {fpath}")
            extra += ["-failures_input", fpath, "-other_location"]
        if cfg["disable_trim"]:
            extra += ["-disable_trim"]

        scen_dir = cfg["out_dir"] / "sim" / scen_name
        for seed in cfg["seeds"]:
            for algo in cfg["algos"]:
                for mapping in cfg["mapping"]:
                    name = run_name(scen_name, algo, mapping, seed)
                    cmd = ([cfg["binary"], "-topo", wl["topo"], "-tm", wl["tm"],
                            "-end", str(cfg["end_us"]), "-seed", str(seed),
                            "-load_balancing_algo", algo]
                           + cfg["common_args"] + extra
                           + (["-connections_mapping"] if mapping else [])
                           + ["-reps_stats_csv", out / f"{name}.csv"])
                    meta = {"scenario": scen_name, "workload": scen["workload"],
                            "ref": scen.get("ref"), "algo": algo,
                            "mapping": "on" if mapping else "off", "seed": seed,
                            "failures_input": scen.get("failures_input"),
                            "cwd": str(scen_dir / name),
                            "cmd": [str(c) for c in cmd]}
                    jobs.append({"name": name, "cmd": cmd, "meta": meta,
                                 "scen_dir": scen_dir, "cwd": scen_dir / name,
                                 "has_failures": bool(scen.get("failures_input"))})
    return jobs


def stage_run(cfg, dry_run, fresh_failures):
    out = cfg["out_dir"] / "runs"
    out.mkdir(parents=True, exist_ok=True)
    jobs = build_jobs(cfg, out)
    print(f"[run] scenarios={list(cfg['scenarios'])}  runs={len(jobs)}")

    for j in jobs:
        cache = j["scen_dir"] / "failures_input" / "saved"
        if not dry_run:
            if fresh_failures and cache.exists():
                shutil.rmtree(cache)
            cache.mkdir(parents=True, exist_ok=True)
            j["cwd"].mkdir(parents=True, exist_ok=True)

    def one(j):
        if not dry_run:
            (out / f"{j['name']}.json").write_text(json.dumps(j["meta"], indent=1))
        rc, dt = run_cmd(j["cmd"], out / f"{j['name']}.log", cfg["timeout_s"], dry_run, cwd=j["cwd"])
        if not dry_run:
            meta = dict(j["meta"], rc=rc, wall_s=round(dt, 1))
            (out / f"{j['name']}.json").write_text(json.dumps(meta, indent=1))
        return rc, dt

    # Phase 1: for every failure scenario without a cached placement, run one job alone
    # so it generates and saves the failure placement (like run_failures.py --cache on).
    phase1, seen = [], set()
    for j in jobs:
        cache = j["scen_dir"] / "failures_input" / "saved"
        if j["has_failures"] and j["scen_dir"] not in seen:
            seen.add(j["scen_dir"])
            if dry_run or not any(cache.glob("saved_*")):
                phase1.append(j)
    phase2 = [j for j in jobs if j not in phase1]

    with ThreadPoolExecutor(max_workers=cfg["jobs"]) as ex:
        if phase1:
            print(f"[run] phase 1: generating failure placements ({len(phase1)} runs)")
            for j, f in [(j, ex.submit(one, j)) for j in phase1]:
                rc, dt = f.result()
                saved = sorted(p.name for p in (j["scen_dir"] / "failures_input" / "saved").glob("saved_*"))
                print(f"  {j['name']:44s} rc={rc} {dt:.1f}s  cached={saved or 'NONE'}")
        print(f"[run] phase 2: {len(phase2)} runs")
        for j, f in [(j, ex.submit(one, j)) for j in phase2]:
            rc, dt = f.result()
            print(f"  {j['name']:44s} rc={rc} {dt:.1f}s")


